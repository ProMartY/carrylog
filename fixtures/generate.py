"""Generate CarryLog fixtures or a proof for a file in an ordered history."""

import argparse
from functools import cache
from hashlib import sha256
import json
from pathlib import Path
import subprocess


CAPACITY = 65_536


def word(value):
    return value.to_bytes(32, "big")


def hex_word(data):
    return "0x" + data.hex()


def split_point(size):
    return 1 << ((size - 1).bit_length() - 1)


def make_tree(openssl):
    @cache
    def keccak(message):
        return subprocess.run(
            [openssl, "dgst", "-keccak-256", "-binary"],
            input=message,
            stdout=subprocess.PIPE,
            check=True,
        ).stdout

    # Known answers guard against selecting NIST SHA3-256 or KMAC by accident.
    for message, expected in (
        (b"", "c5d2460186f7233c927e7db2dcc703c0e500b653ca82273b7bfad8045d85a470"),
        (b"abc", "4e03657aea45a94fc7d47ba826c8d667c0d1e6e33a64a036ec44f58fa12d6c45"),
    ):
        if keccak(message).hex() != expected:
            raise ValueError("OpenSSL failed the Keccak-256 known-answer check")

    @cache
    def root(digests):
        size = len(digests)
        if size == 0:
            return keccak(b"")
        if size == 1:
            return keccak(word(0) + digests[0])
        split = split_point(size)
        return keccak(word(1) + root(digests[:split]) + root(digests[split:]))

    def path(digests, index):
        if len(digests) == 1:
            return []
        split = split_point(len(digests))
        if index < split:
            return path(digests[:split], index) + [root(digests[split:])]
        return path(digests[split:], index - split) + [root(digests[:split])]

    return root, path


def proof_fields(digests, index, root, path):
    return {
        "size": len(digests),
        "root": hex_word(root(digests)),
        "index": index,
        "digest": hex_word(digests[index]),
        "path": [hex_word(sibling) for sibling in path(digests, index)],
    }


def file_digest(path):
    if not path.is_file():
        raise ValueError(f"expected a regular file: {path}")
    digest = sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.digest()


def build_vectors(openssl):
    root, path = make_tree(openssl)

    def valid_case(name, digests, index):
        return {"name": name, **proof_fields(digests, index, root, path), "valid": True}

    def invalid_case(case, name, **changes):
        return {**case, **changes, "name": name, "valid": False}

    small = tuple(word(n) for n in range(1, 10))
    seven = small[:7]
    seven_proofs = [valid_case(f"seven-index-{i}", seven, i) for i in range(7)]
    target = seven_proofs[2]
    full = (word(0x42),) * CAPACITY
    full_proof = valid_case("capacity-last-index", full, len(full) - 1)

    return {
        "format": "carrylog-v1",
        "encoding": "Hex strings represent 32-byte big-endian words. Paths run from leaf to root.",
        "prefix_digests": [hex_word(digest) for digest in small],
        "prefix_roots": [hex_word(root(small[:size])) for size in range(10)],
        "proof_cases": [
            valid_case("singleton-empty-path", small[:1], 0),
            valid_case("zero-digest", (word(0),), 0),
            *seven_proofs,
            invalid_case(target, "changed-artifact-digest", digest=hex_word(word(99))),
            invalid_case(target, "wrong-index", index=3),
            invalid_case(target, "index-equals-size", index=7),
            invalid_case(target, "different-checkpoint-root", root=hex_word(root(small[:8]))),
            invalid_case(target, "missing-sibling", path=target["path"][:-1]),
            invalid_case(target, "extra-sibling", path=[*target["path"], hex_word(word(0))]),
            invalid_case(target, "modified-sibling", path=[hex_word(word(0)), *target["path"][1:]]),
            invalid_case(target, "empty-checkpoint", size=0, root=hex_word(root(())), index=0, path=[]),
            valid_case("capacity-minus-one-last-index", full[:-1], len(full) - 2),
            full_proof,
            invalid_case(full_proof, "size-above-capacity", size=len(full) + 1),
        ],
        "boundary_input": {
            "digest": hex_word(full[0]),
            "repeat": len(full),
        },
    }


def render_fe(vectors):
    lines = [
        "// Generated by fixtures/generate.py from independent OpenSSL vectors.",
        "use core::ptr::MemVec",
        "use ingot::verify_checkpoint",
        "use std::abi::DynArray",
        "",
        "fn siblings_from_words<const N: usize>(words: [u256; N]) -> DynArray<u256> {",
        "    var siblings = MemVec<u256>::new()",
        "    var i: usize = 0",
        "    while i < N {",
        "        siblings.push(words[i])",
        "        i += 1",
        "    }",
        "    DynArray::from_slice(siblings.as_slice())",
        "}",
    ]
    for case in vectors["proof_cases"]:
        name = case["name"].replace("-", "_")
        predicate = "" if case["valid"] else "!"
        lines.extend([
            "",
            "#[test]",
            f"fn proof_vector_{name}() {{",
            "    assert!(",
            f"        {predicate}verify_checkpoint(",
            f"            size: {case['size']},",
            f"            root: {case['root']},",
            f"            index: {case['index']},",
            f"            digest: {hex(int(case['digest'], 16))},",
        ])
        if case["path"]:
            lines.extend(["            siblings: siblings_from_words(", "                words: ["])
            lines.extend(f"                    {sibling}," for sibling in case["path"])
            lines.extend(["                ],", "            ),"])
        else:
            lines.append("            siblings: siblings_from_words(words: []),")
        lines.extend(["        ),", "    )", "}"])
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--openssl", default="openssl", help="Path to OpenSSL with KECCAK-256 support")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="Compare generated files without writing")
    mode.add_argument("--proof-index", type=int, help="Emit a proof for this zero-based artifact index")
    parser.add_argument("artifacts", type=Path, nargs="*", help="Artifact files in append order")
    args = parser.parse_args()
    if args.proof_index is not None:
        if len(args.artifacts) > CAPACITY:
            parser.error(f"the journal can contain at most {CAPACITY} files")
        if not 0 <= args.proof_index < len(args.artifacts):
            parser.error("--proof-index must identify one of the supplied files")
        try:
            digests = tuple(file_digest(file) for file in args.artifacts)
            root, path = make_tree(args.openssl)
            proof = proof_fields(digests, args.proof_index, root, path)
        except (OSError, ValueError, subprocess.CalledProcessError) as error:
            parser.exit(1, f"Could not build proof: {error}\n")
        print(json.dumps({"format": "carrylog-v1", **proof}, indent=2))
        return
    if args.artifacts:
        parser.error("artifact files require --proof-index")
    fixture_dir = Path(__file__).parent
    vectors = build_vectors(args.openssl)
    for target, rendered in (
        (fixture_dir / "vectors.json", json.dumps(vectors, indent=2) + "\n"),
        (fixture_dir.parent / "src" / "vector_tests.fe", render_fe(vectors)),
    ):
        if args.check:
            if target.read_text(encoding="utf-8") != rendered:
                parser.exit(1, f"{target.name} differs from the independent generator\n")
        else:
            target.write_text(rendered, encoding="utf-8", newline="\n")
    if args.check:
        print("CarryLog fixture vectors and Fe tests match the independent generator")


if __name__ == "__main__":
    main()
